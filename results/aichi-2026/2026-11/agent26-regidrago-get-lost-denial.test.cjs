'use strict';
const {analyze,copies,INVENTORY}=require('./agent26-regidrago-get-lost-denial.cjs');
let cases=0;
const eq=(a,b,label)=>{cases++;if(JSON.stringify(a)!==JSON.stringify(b))throw Error(label+': '+JSON.stringify(a)+' != '+JSON.stringify(b));};
const throws=(f,label)=>{cases++;let ok=false;try{f()}catch{ok=true}if(!ok)throw Error(label);};
const G='Girafarig LOT 94', M='Mimikyu GRI 58', S='Marshadow UNB 81', W='Wobbuffet PHF 36', V='Shadow Rider Calyrex VMAX CRE 75', L='Latias ex SSP 76', R='Regidrago V SIT 135', D='Dialga-GX UPR 100', K='Kyurem SFA 47', A='Salamence ex JTG 114', B='Mega Dragonite ex ASC 152', P='Dragapult ex TWM 130';
const t=(id,printing,remainingHP)=>({id,printing,remainingHP});
const state={profile:'hood',apexPayable:true,noOtherCombatModifiers:true,bandLive:true,gxUnused:true,nextApexPayable:true,attackerDamage:0,prizesToWin:3,gustBudget:1,firstGustReady:true,secondGustReady:true,active:'g',targets:[t('g',G,90),t('m',M,70),t('s',S,80),t('v',V,320),t('l',L,210)]};
const payloads=rank=>{const r=copies(rank);r.splice(r.indexOf(R),1);return r};
const rows=[];
for(const rank of Object.keys(INVENTORY).map(Number)){
 const discard=payloads(rank);
 const over=analyze({rank,state:{...state,discard}});
 const trim=analyze({rank,state:{...state,discard,targets:state.targets.filter(x=>x.id!=='s')}});
 const lock=analyze({rank,state:{...state,profile:'lockbridge',discard,targets:state.targets.map(x=>x.id==='s'?t('w',W,110):x)}});
 eq(over.baseline.current.win,true,'baseline exposed rank '+rank);
 eq(trim.safeEnvelope.length>0,true,'trim allows permanent denial '+rank);
 eq(over.safeEnvelope.length===0,lock.safeEnvelope.length===0,'Wobbuffet substitutes 110 HP '+rank);
 rows.push({rank,over,trim,lock});
}
eq(rows.filter(x=>x.over.safeEnvelope.length===0).map(x=>x.rank),[12,13,14,20,27,32],'no two-card answer on three small supports');
const r13=rows.find(x=>x.rank===13);
eq(r13.trim.safeEnvelope.some(x=>x.cards.includes(D)&&x.cards.includes(A)),true,'rank13 trim Dialga + Salamence');
const r14=rows.find(x=>x.rank===14);
eq(r14.trim.safeEnvelope.some(x=>x.cards.includes(D)&&x.cards.includes(B)),true,'rank14 trim Dialga + Mega Dragonite');
const r12=rows.find(x=>x.rank===12);
eq(r12.trim.safeEnvelope.some(x=>x.cards[0]===D&&x.cards[1]===D),true,'two Dialga copies consume both targets');
const partial=analyze({rank:12,state:{...state,discard:[D,K,P],targets:state.targets.filter(x=>x.id!=='s')}});
const row=partial.rows.find(x=>x.cards.includes(D)&&x.cards.includes(K));
eq(row.current.win,false,'temporarily remove current two-turn line');
eq(row.envelope.win,true,'second source Dialga remains possible');
const noGust=analyze({rank:13,state:{...state,discard:payloads(13),gustBudget:0,firstGustReady:false,secondGustReady:false}});
eq(noGust.safeEnvelope.length>0,true,'no real gust changes denial geometry');
const noBand=analyze({rank:13,state:{...state,discard:payloads(13),bandLive:false}});
eq(noBand.safeEnvelope.length>0,true,'no Band removes exact 320 damage breakpoint');
const lost=analyze({rank:13,lost:[D],state:{...state,discard:payloads(13).filter(x=>x!==D)}});
eq(lost.safeEnvelope.some(x=>x.cards.includes(K)&&x.cards.includes(A)),true,'already Lost Dialga frees bandwidth');
throws(()=>analyze({rank:13,state:{...state,discard:[D,D,K]}}),'reject duplicate singleton');
throws(()=>analyze({rank:13,locked:[],state:{...state,discard:[D,K]}}),'reserve evolution base');
throws(()=>analyze({rank:10,state:{...state,attackerDamage:220,discard:payloads(10)}}),'Kaiser self-KO not modeled');
module.exports={cases,rows,partial,noGust,noBand,lost,state};
if(require.main===module)console.log(cases+' checks passed');
